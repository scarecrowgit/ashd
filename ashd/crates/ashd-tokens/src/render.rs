            assert!(out.trim_end().ends_with("return M"));
            assert_eq!(out.matches("local M = {}").count(), 1);
            assert!(out.contains("function M.apply()"));
            // every colour the highlight code reads exists in M.colors
            let tbl: std::collections::HashSet<String> = out
                .split("M.colors = {")
                .nth(1)
                .unwrap()
                .split("\n}")
                .next()
                .unwrap()
                .lines()
                .filter_map(|l| l.trim().split(" = ").next().map(str::to_string))
                .filter(|k| !k.is_empty())
                .collect();
            assert_eq!(tbl.len(), 17 + derived(&t.colors).len());
            let body = out.split("function M.highlights()").nth(1).unwrap();
            let mut used = 0;
            for part in body.split("c.").skip(1) {
                let key: String =
                    part.chars().take_while(|ch| ch.is_ascii_alphanumeric() || *ch == '_').collect();
                assert!(tbl.contains(&key), "nvim lua uses unknown colour c.{key}");
                used += 1;
            }
