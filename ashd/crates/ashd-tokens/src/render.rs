//! Theme files for the rest of the desktop, rendered from [`Tokens`] as `String`s.
//! [`crate::state::apply`] writes them to `$XDG_STATE_HOME/ashd/generated/<file_name>`;
//! the NixOS/home-manager config includes them from there (contract in ARCHITECTURE.md
//! "Theme files").
//!
//! | target | consumer | validated by |
//! |---|---|---|
//! | [`kitty`] | `include` in kitty.conf | tests (every key is a known kitty option) |
//! | [`starship`] | `[palettes.ashd]` table | tests (TOML shape) |
//! | [`nvim_lua`] | `dofile(..).apply()` | `luac`/nvim in the dev environment, tests (balanced) |
//! | [`gtk_css`] | `@import` from gtk.css (adw-gtk3, libadwaita) | tests (declaration shape) |
//! | [`niri_kdl`] | `include` in niri's config | `niri validate` (ignored test, `NIRI_BIN`) |

use crate::{Colors, LayoutVariant, Rgba, Tokens, WindowMode, metrics};

/// One generated theme file.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Target {
    /// kitty `include`-able colours. Reload: `kill -SIGUSR1 $(pidof kitty)`.
    Kitty,
    /// starship `[palettes.ashd]` table (select with `palette = "ashd"`).
    Starship,
    /// Complete starship config: the NixOS base config (`/etc/ashd/starship-base.toml`) plus
    /// the palette table, ready for `STARSHIP_CONFIG`. Without a base file: a minimal
    /// `palette = "ashd"` header plus the table. Written by [`crate::state::apply`];
    /// [`Target::render`] gives the base-less form.
    StarshipConfig,
    /// Neovim lua module returning the palette and an `apply()` that sets all highlights.
    Nvim,
    /// GTK 3/4 + libadwaita `@define-color`s and radius rules.
    Gtk,
    /// niri KDL fragment (layout colours, gaps, title strips, canvas grid, corner radius, backdrop) for `include`.
    Niri,
}

impl Target {
    pub const ALL: [Target; 6] =
        [Self::Kitty, Self::Starship, Self::Nvim, Self::Gtk, Self::Niri, Self::StarshipConfig];

    pub fn file_name(self) -> &'static str {
        match self {
            Self::Kitty => "kitty.conf",
            Self::Starship => "starship-palette.toml",
            Self::StarshipConfig => "starship.toml",
            Self::Nvim => "nvim.lua",
            Self::Gtk => "gtk.css",
            Self::Niri => "niri.kdl",
        }
    }

    pub fn render(self, t: &Tokens) -> String {
        match self {
            Self::Kitty => kitty(t),
            Self::Starship => starship(t),
            Self::StarshipConfig => starship_full(t, None),
            Self::Nvim => nvim_lua(t),
            Self::Gtk => gtk_css(t),
            Self::Niri => niri_kdl(t),
        }
    }
}

fn header(comment: &str, t: &Tokens) -> String {
    format!("{comment} ashd theme `{}` — generated by `ashd theme apply`; do not edit.\n", t.name)
}

/// Linear mix in sRGB: `a` at `1 - f`, `b` at `f`. Result is opaque.
pub fn mix(a: Rgba, b: Rgba, f: f32) -> Rgba {
    let m = |x: u8, y: u8| (x as f32 + (y as f32 - x as f32) * f.clamp(0.0, 1.0)).round() as u8;
    Rgba { r: m(a.r, b.r), g: m(a.g, b.g), b: m(a.b, b.b), a: 0xFF }
}

/// The 16 ANSI colours derived from the semantic tokens.
///
/// 0 black = `line`, 1 red = `err`, 2 green = `ok`, 3 yellow = `warn`, 4 blue = `info`,
/// 5 magenta = `err`/`info` mix, 6 cyan = `info`/`ok` mix, 7 white = `fg-muted`;
/// 8 bright black = `syn-comment`, 9..14 = the normal colour 25 % towards `fg`, 15 = `fg`.
/// Colours 1..6 keep >= 4.5:1 against `surface-2` in every theme (tested).
pub fn ansi(c: &Colors) -> [Rgba; 16] {
    let magenta = mix(c.err, c.info, 0.5);
    let cyan = mix(c.info, c.ok, 0.5);
    let normal = [c.line, c.err, c.ok, c.warn, c.info, magenta, cyan, c.fg_muted];
    let bright = |x: Rgba| mix(x, c.fg, 0.25);
    [
        normal[0],
        normal[1],
        normal[2],
        normal[3],
        normal[4],
        normal[5],
        normal[6],
        normal[7],
        c.syn_comment,
        bright(c.err),
        bright(c.ok),
        bright(c.warn),
        bright(c.info),
        bright(magenta),
        bright(cyan),
        c.fg,
    ]
}

/// Tints derived from the tokens for editors (selection, search, diff and diagnostic
/// backgrounds): `(name, colour)`, all blended into `surface-2`.
pub fn derived(c: &Colors) -> [(&'static str, Rgba); 12] {
    let on = |x: Rgba, f: f32| mix(c.surface_2, x, f);
    [
        ("visual", mix(c.line, c.accent, 0.25)),
        ("search", on(c.accent, 0.35)),
        ("diff_add", on(c.ok, 0.18)),
        ("diff_change", on(c.info, 0.15)),
        ("diff_delete", on(c.err, 0.18)),
        ("diff_text", on(c.info, 0.32)),
        ("diag_err_bg", on(c.err, 0.12)),
        ("diag_warn_bg", on(c.warn, 0.12)),
        ("diag_info_bg", on(c.info, 0.12)),
        ("diag_hint_bg", on(c.fg_muted, 0.12)),
        ("diag_ok_bg", on(c.ok, 0.12)),
        ("selection", mix(c.surface_2, c.accent, 0.3)),
    ]
}

