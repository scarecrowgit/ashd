pub fn kitty(t: &Tokens) -> String {
    let c = &t.colors;
    let mut s = header("#", t);
    let kv = |s: &mut String, k: &str, v: Rgba| s.push_str(&format!("{k:<24}{}\n", v.hex()));
    // Terminals are windows: `--surface-2` background (sys-05).
    kv(&mut s, "foreground", c.fg);
    kv(&mut s, "background", c.surface_2);
    kv(&mut s, "selection_foreground", c.on_accent);
    kv(&mut s, "selection_background", c.accent);
    kv(&mut s, "cursor", c.accent);
    kv(&mut s, "cursor_text_color", c.on_accent);
    kv(&mut s, "url_color", c.info);
    kv(&mut s, "active_border_color", c.accent);
    kv(&mut s, "inactive_border_color", c.frame);
    kv(&mut s, "bell_border_color", c.warn);
    kv(&mut s, "visual_bell_color", c.warn);
    kv(&mut s, "active_tab_foreground", c.on_accent);
    kv(&mut s, "active_tab_background", c.accent);
    kv(&mut s, "inactive_tab_foreground", c.fg_muted);
    kv(&mut s, "inactive_tab_background", c.surface);
    kv(&mut s, "tab_bar_background", c.surface);
    kv(&mut s, "tab_bar_margin_color", c.surface);
    kv(&mut s, "mark1_foreground", c.on_accent);
    kv(&mut s, "mark1_background", c.accent);
    kv(&mut s, "mark2_foreground", c.on_accent);
    kv(&mut s, "mark2_background", c.info);
    kv(&mut s, "mark3_foreground", c.on_accent);
    kv(&mut s, "mark3_background", c.warn);
    for (i, col) in ansi(c).iter().enumerate() {
        kv(&mut s, &format!("color{i}"), *col);
    }
    s
}

// ── starship ──────────────────────────────────────────────────────────────────

/// `[palettes.ashd]`: the 17 tokens (`surface_2`), the ANSI names starship styles use
/// (`red`, `bright-green` …, so stock modules pick up the theme) and `accent`-based
/// helpers. Select it with `palette = "ashd"` at the top of starship.toml.
pub fn starship(t: &Tokens) -> String {
    let c = &t.colors;
    let mut s = header("#", t);
    s.push_str("# starship.toml:  palette = \"ashd\"   (then append this file)\n");
    s.push_str("[palettes.ashd]\n");
    for (name, col) in c.iter() {
        s.push_str(&format!("{} = \"{}\"\n", name.replace('-', "_"), col.hex()));
    }
    const NAMES: [&str; 16] = [
        "black",
        "red",
        "green",
        "yellow",
        "blue",
        "purple",
        "cyan",
        "white",
        "bright-black",
        "bright-red",
        "bright-green",
        "bright-yellow",
        "bright-blue",
        "bright-purple",
        "bright-cyan",
        "bright-white",
    ];
    for (name, col) in NAMES.iter().zip(ansi(c)) {
        s.push_str(&format!("{name} = \"{}\"\n", col.hex()));
    }
    s
}

/// A complete starship config: `base` (the NixOS config without a palette table; it may
/// use the palette names `accent`, `fg`, `ok`, `warn`, `err`, `info`, …) followed by the
/// [`starship`] palette table. A top-level `palette = "ashd"` is prepended unless `base`
/// already selects a palette. With no base: that header and the table only.
pub fn starship_full(t: &Tokens, base: Option<&str>) -> String {
    let table = starship(t);
    let mut s = String::new();
    let base = base.map(str::trim_end).filter(|b| !b.is_empty());
    let selects = base.is_some_and(|b| b.lines().any(|l| l.trim_start().starts_with("palette")));
    if !selects {
        s.push_str("palette = \"ashd\"\n");
    }
    if let Some(b) = base {
        s.push_str(b);
        s.push_str("\n\n");
    }
    s.push_str(&table);
    s
}

// ── neovim ────────────────────────────────────────────────────────────────────

/// The Lua module: `M.name`, `M.fonts`, `M.colors` (17 tokens + [`derived`] tints),
/// `M.ansi`, `M.highlights()`, `M.lualine`, `M.apply()`. The static part lives in
/// `src/nvim_apply.lua`.
pub fn nvim_lua(t: &Tokens) -> String {
    let c = &t.colors;
    let mut s = header("--", t);
    s.push_str("local M = {}\n\n");
    s.push_str(&format!("M.name = \"{}\"\n", t.name));
    s.push_str(&format!("M.fonts = {{ sans = \"{}\", mono = \"{}\" }}\n", t.fonts.sans, t.fonts.mono));
    s.push_str("M.colors = {\n");
    for (name, col) in c.iter() {
        s.push_str(&format!("  {} = \"{}\",\n", name.replace('-', "_"), col.hex()));
    }
    for (name, col) in derived(c) {
        s.push_str(&format!("  {name} = \"{}\",\n", col.hex()));
    }
    s.push_str("}\nM.ansi = {");
    for (i, col) in ansi(c).iter().enumerate() {
        s.push_str(&format!("{}\"{}\"", if i == 0 { " " } else { ", " }, col.hex()));
    }
    s.push_str(" }\n\n");
    s.push_str(include_str!("nvim_apply.lua"));
    s
}

